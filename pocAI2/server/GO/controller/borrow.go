// CheckAssetAvailability verifies:
// 1. Table public.assets: existence, tenant ownership, and availability status (not borrowed or maintenance)
// 2. Table public.hold_borrow: asset not currently held in unsubmitted queue (status = 'held')
// 3. Table public.borrow_transactions + borrow_items: asset not in pending_approval, approved, or active loan
func CheckAssetAvailability(ctx context.Context, assetID string, tenant string, excludeHoldID string, excludeTrxID string) (bool, string) {
	assetID = strings.TrimSpace(assetID)
	if assetID == "" {
		return false, "Asset ID tidak boleh kosong"
	}

	// 1. Cek tabel public.assets
	var aName, aStatus, aPerusahaan string
	err := DB.QueryRow(ctx, `
		SELECT name, COALESCE(status, 'available'), COALESCE(perusahaan, '')
		FROM public.assets
		WHERE asset_id ILIKE $1
		LIMIT 1
	`, assetID).Scan(&aName, &aStatus, &aPerusahaan)
	if err != nil {
		return false, fmt.Sprintf("Aset '%s' tidak ditemukan dalam database aset", assetID)
	}

	if tenant != "" && aPerusahaan != "" && !strings.EqualFold(aPerusahaan, tenant) {
		return false, fmt.Sprintf("Aset '%s' (%s) terdaftar pada tenant '%s', tidak dapat dipinjam oleh tenant '%s'", assetID, aName, aPerusahaan, tenant)
	}

	if strings.EqualFold(aStatus, "borrowed") {
		return false, fmt.Sprintf("Aset '%s' (%s) saat ini sedang berstatus DIPINJAM", assetID, aName)
	}
	if strings.EqualFold(aStatus, "maintenance") || strings.EqualFold(aStatus, "rusak") {
		return false, fmt.Sprintf("Aset '%s' (%s) sedang dalam status '%s'", assetID, aName, aStatus)
	}

	// 2. Cek tabel public.hold_borrow (apakah sedang dalam antrean hold yang belum submit)
	holdQuery := `
		SELECT h.hold_code, h.borrower_name
		FROM public.hold_borrow h
		WHERE h.status = 'held'
		  AND h.items::text ILIKE '%' || $1 || '%'
	`
	var holdArgs = []any{assetID}
	if excludeHoldID != "" {
		holdQuery += " AND h.id::text != $2 AND h.hold_code != $2"
		holdArgs = append(holdArgs, excludeHoldID)
	}
	holdQuery += " LIMIT 1"

	var holdCode, holdBorrower string
	if errHold := DB.QueryRow(ctx, holdQuery, holdArgs...).Scan(&holdCode, &holdBorrower); errHold == nil && holdCode != "" {
		return false, fmt.Sprintf("Aset '%s' (%s) saat ini sedang di-hold oleh %s (kode hold: %s)", assetID, aName, holdBorrower, holdCode)
	}

	// 3. Cek tabel public.borrow_transactions + public.borrow_items (apakah sedang pending_approval / active)
	trxQuery := `
		SELECT t.transaction_code, t.borrower_name, t.status
		FROM public.borrow_items bi
		JOIN public.borrow_transactions t ON bi.transaction_id = t.id
		WHERE bi.asset_id ILIKE $1
		  AND COALESCE(bi.status, '') != 'rejected'
		  AND t.status IN ('pending_approval', 'approved', 'active')
	`
	var trxArgs = []any{assetID}
	if excludeTrxID != "" {
		trxQuery += " AND t.id::text != $2 AND t.transaction_code != $2"
		trxArgs = append(trxArgs, excludeTrxID)
	}
	trxQuery += " LIMIT 1"

	var trxCode, trxBorrower, trxStatus string
	if errTrx := DB.QueryRow(ctx, trxQuery, trxArgs...).Scan(&trxCode, &trxBorrower, &trxStatus); errTrx == nil && trxCode != "" {
		statusLabel := "menunggu approval"
		if trxStatus == "active" {
			statusLabel = "sedang aktif dipinjam"
		} else if trxStatus == "approved" {
			statusLabel = "telah disetujui"
		}
		return false, fmt.Sprintf("Aset '%s' (%s) %s dalam transaksi %s oleh %s", assetID, aName, statusLabel, trxCode, trxBorrower)
	}

	return true, ""
}

