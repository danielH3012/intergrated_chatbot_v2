// UpdateAnomalySettings handles POST /api/borrow/anomalies/settings
func UpdateAnomalySettings(c *fiber.Ctx) error {
	role := ""
	if id := middleware.RequestIdentity(c); id != nil {
		role = strings.ToLower(strings.TrimSpace(id.Role))
	}
	if role == "" {
		role = strings.ToLower(strings.TrimSpace(c.Get("X-User-Role")))
	}
	if role == "" {
		role = strings.ToLower(strings.TrimSpace(c.Get("X-Role")))
	}
	if role == "" {
		role = strings.ToLower(strings.TrimSpace(c.Query("role")))
	}

	if role != "admin" {
		return c.Status(403).JSON(fiber.Map{
			"error": "Akses ditolak: Hanya pengguna dengan role Administrator yang diizinkan untuk mengubah konfigurasi dan threshold peminjaman.",
		})
	}

	var payload AnomalyThresholds
	if err := c.BodyParser(&payload); err != nil {
		return c.Status(400).JSON(fiber.Map{"error": "Format payload tidak valid"})
	}

	tenant := strings.TrimSpace(payload.CompanyName)
	if tenant == "" {
		tenant = ResolveTenantCompany(c)
	}

	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	updated, err := UpdateTenantThresholds(ctx, tenant, payload)
	if err != nil {
		return c.Status(500).JSON(fiber.Map{"error": "Gagal menyimpan threshold ke database: " + err.Error()})
	}

	return c.JSON(fiber.Map{
		"message":  fmt.Sprintf("Pengaturan threshold peminjaman untuk tenant '%s' berhasil diperbarui", tenant),
		"tenant":   tenant,
		"settings": updated,
	})
}


