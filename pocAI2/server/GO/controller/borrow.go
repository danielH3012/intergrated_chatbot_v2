// GetBorrowApprovals handles GET /api/borrow/approvals
func GetBorrowApprovals(c *fiber.Ctx) error {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	_, userCompany := resolveUserContext(c)
	if userCompany == "" {
		userCompany = strings.TrimSpace(c.Get("X-Company"))
	}

	// group_name is the user division/department, only filter if explicitly passed as query param
	groupName := strings.TrimSpace(c.Query("group_name"))
	borrowerID := strings.TrimSpace(c.Query("borrower_id"))
	if borrowerID == "" {
		borrowerID = strings.TrimSpace(c.Get("X-User-ID"))
	}
	role := strings.ToLower(strings.TrimSpace(c.Query("role")))
	if role == "" {
		role = strings.ToLower(strings.TrimSpace(c.Get("X-Role")))
	}
	if role == "" {
		role = strings.ToLower(strings.TrimSpace(c.Get("X-User-Role")))
	}
	if role == "" {
		if id := middleware.RequestIdentity(c); id != nil && id.Role != "" {
			role = strings.ToLower(strings.TrimSpace(id.Role))
		}
	}

	query := `
		SELECT t.id, t.transaction_code, t.borrower_id, t.borrower_name, 
		       COALESCE(t.manager_id, ''), t.manager_name, t.group_name, 
		       t.request_date, t.status, COUNT(DISTINCT i.id) AS item_count
		FROM public.borrow_transactions t
		LEFT JOIN public.borrow_items i ON t.id = i.transaction_id
		LEFT JOIN public.assets a ON i.asset_id = a.asset_id
		LEFT JOIN public.users u ON (t.borrower_id = u.id OR LOWER(t.borrower_name) = LOWER(u.username))
		WHERE t.status != 'rejected'
	`
	var args []any
	argIdx := 1

	// Strict Tenant Isolation: only show approvals belonging to the authenticated tenant/company
	if userCompany != "" {
		query += fmt.Sprintf(` AND (
			LOWER(TRIM(u.company)) = LOWER(TRIM($%d))
			OR LOWER(TRIM(t.group_name)) = LOWER(TRIM($%d))
		)`, argIdx, argIdx)
		args = append(args, userCompany)
		argIdx++
	}

	// Group filter (division)
	if groupName != "" {
		query += fmt.Sprintf(" AND LOWER(t.group_name) = LOWER($%d)", argIdx)
		args = append(args, groupName)
		argIdx++
	}

	// Role scoping: non-admin only sees their own transactions
	if role != "admin" && borrowerID != "" {
		query += fmt.Sprintf(" AND (t.borrower_id = $%d OR LOWER(t.borrower_name) = LOWER($%d))", argIdx, argIdx)
		args = append(args, borrowerID)
		argIdx++
	}

	query += `
		GROUP BY t.id, t.transaction_code, t.borrower_id, t.borrower_name, 
		         t.manager_id, t.manager_name, t.group_name, t.request_date, t.status
		ORDER BY t.request_date DESC
	`

	rows, err := DB.Query(ctx, query, args...)
	if err != nil {
		return c.Status(500).JSON(fiber.Map{"error": err.Error()})
	}
	defer rows.Close()

	result := []BorrowApprovalTransaction{}
	for rows.Next() {
		var item BorrowApprovalTransaction
		if err := rows.Scan(
			&item.ID, &item.TransactionCode, &item.BorrowerID, &item.BorrowerName,
			&item.ManagerID, &item.ManagerName, &item.GroupName,
			&item.RequestDate, &item.Status, &item.ItemCount,
		); err != nil {
			return c.Status(500).JSON(fiber.Map{"error": err.Error()})
		}
		result = append(result, item)
	}

	return c.JSON(fiber.Map{"transactions": result})
}

