// GetBorrowHistoryRecommendations handles GET /api/borrow/history/recommendations
func GetBorrowHistoryRecommendations(c *fiber.Ctx) error {
	ctx, cancel := context.WithTimeout(context.Background(), 8*time.Second)
	defer cancel()

	_, userCompany := resolveUserContext(c)
	if userCompany == "" {
		userCompany = strings.TrimSpace(c.Get("X-Company"))
	}

	searchQuery := strings.TrimSpace(c.Query("query"))
	if searchQuery == "" {
		searchQuery = strings.TrimSpace(c.Query("keyword"))
	}
	category := strings.TrimSpace(c.Query("category"))
	location := strings.TrimSpace(c.Query("location"))
	groupName := strings.TrimSpace(c.Query("group_name"))

	limit := 5
	if l := c.Query("limit"); l != "" {
		if val, err := strconv.Atoi(l); err == nil && val > 0 && val <= 20 {
			limit = val
		}
	}

	var args []any
	argIdx := 1

	sqlQuery := `
		SELECT 
			MAX(COALESCE(a.name, i.asset_id)) AS asset_name,
			MAX(COALESCE(a.category, '')) AS category,
			MAX(COALESCE(a.model_type, '')) AS model_type,
			MAX(COALESCE(a.brand, '')) AS brand,
			COUNT(i.id) AS borrow_count,
			COUNT(DISTINCT t.borrower_id) AS distinct_borrowers,
			ROUND(AVG(COALESCE(i.duration_days, 14)))::int AS avg_duration_days,
			COALESCE(TO_CHAR(MAX(t.request_date), 'YYYY-MM-DD"T"HH24:MI:SSOF'), '') AS last_borrowed_date
		FROM public.borrow_items i
		JOIN public.borrow_transactions t ON i.transaction_id = t.id
		LEFT JOIN public.assets a ON i.asset_id = a.asset_id
		LEFT JOIN public.users u ON (t.borrower_id = u.id OR LOWER(t.borrower_name) = LOWER(u.username))
		WHERE t.status != 'rejected'
	`

	if userCompany != "" {
		sqlQuery += fmt.Sprintf(` AND (
			LOWER(TRIM(u.company)) = LOWER(TRIM($%d))
			OR LOWER(TRIM(t.group_name)) = LOWER(TRIM($%d))
			OR LOWER(TRIM(a.perusahaan)) = LOWER(TRIM($%d))
			OR EXISTS (
				SELECT 1 FROM public.perusahaan p
				WHERE (LOWER(TRIM(p.nama_perusahaan)) = LOWER(TRIM($%d)) OR p.id_perusahaan::text = LOWER(TRIM($%d)))
				  AND (a.perusahaan = p.id_perusahaan::text OR LOWER(TRIM(a.perusahaan)) = LOWER(TRIM(p.nama_perusahaan)) OR u.company = p.id_perusahaan::text OR LOWER(TRIM(u.company)) = LOWER(TRIM(p.nama_perusahaan)))
			)
		)`, argIdx, argIdx, argIdx, argIdx, argIdx)
		args = append(args, userCompany)
		argIdx++
	}

	if groupName != "" {
		sqlQuery += fmt.Sprintf(" AND LOWER(t.group_name) ILIKE '%%' || LOWER($%d) || '%%'", argIdx)
		args = append(args, groupName)
		argIdx++
	}

	if category != "" {
		sqlQuery += fmt.Sprintf(" AND LOWER(a.category) ILIKE '%%' || LOWER($%d) || '%%'", argIdx)
		args = append(args, category)
		argIdx++
	}

	if location != "" {
		sqlQuery += fmt.Sprintf(" AND LOWER(a.location) ILIKE '%%' || LOWER($%d) || '%%'", argIdx)
		args = append(args, location)
		argIdx++
	}

	if searchQuery != "" {
		sqlQuery += fmt.Sprintf(` AND (
			LOWER(a.name) ILIKE '%%' || LOWER($%d) || '%%'
			OR LOWER(a.category) ILIKE '%%' || LOWER($%d) || '%%'
			OR LOWER(a.model_type) ILIKE '%%' || LOWER($%d) || '%%'
			OR LOWER(a.brand) ILIKE '%%' || LOWER($%d) || '%%'
			OR LOWER(a.location) ILIKE '%%' || LOWER($%d) || '%%'
			OR LOWER(t.group_name) ILIKE '%%' || LOWER($%d) || '%%'
		)`, argIdx, argIdx, argIdx, argIdx, argIdx, argIdx)
		args = append(args, searchQuery)
		argIdx++
	}

	sqlQuery += fmt.Sprintf(`
		GROUP BY LOWER(TRIM(COALESCE(a.name, i.asset_id)))
		ORDER BY borrow_count DESC, MAX(t.request_date) DESC
		LIMIT $%d
	`, argIdx)
	args = append(args, limit)

	rows, err := DB.Query(ctx, sqlQuery, args...)
	if err != nil {
		return c.Status(500).JSON(fiber.Map{"error": err.Error()})
	}
	defer rows.Close()

	var recs []BorrowHistoryRecommendation

	for rows.Next() {
		var r BorrowHistoryRecommendation
		if err := rows.Scan(
			&r.AssetName, &r.Category, &r.ModelType, &r.Brand,
			&r.BorrowCount, &r.DistinctBorrowers, &r.AvgDurationDays, &r.LastBorrowedDate,
		); err != nil {
			continue
		}

		r.RecommendationReason = fmt.Sprintf("Paling sering dipinjam dalam riwayat transaksi (%d kali dipinjam oleh %d peminjam berbeda)", r.BorrowCount, r.DistinctBorrowers)

		// Query available stock for this asset name so the AI can provide immediate ready-to-borrow asset_ids
		stockQuery := `
			SELECT a.asset_id 
			FROM public.assets a
			WHERE LOWER(a.name) = LOWER($1) 
			  AND LOWER(COALESCE(a.status, 'available')) IN ('available', 'active')
		`
		stockArgs := []any{r.AssetName}
		if userCompany != "" {
			stockQuery += ` AND (
				LOWER(TRIM(a.perusahaan)) = LOWER(TRIM($2))
				OR EXISTS (
					SELECT 1 FROM public.perusahaan p
					WHERE (LOWER(TRIM(p.nama_perusahaan)) = LOWER(TRIM($2)) OR p.id_perusahaan::text = LOWER(TRIM($2)))
					  AND (a.perusahaan = p.id_perusahaan::text OR LOWER(TRIM(a.perusahaan)) = LOWER(TRIM(p.nama_perusahaan)))
				)
			)`
			stockArgs = append(stockArgs, userCompany)
		}
		stockQuery += " LIMIT 10"

		stockRows, stockErr := DB.Query(ctx, stockQuery, stockArgs...)
		if stockErr == nil {
			var samples []string
			for stockRows.Next() {
				var sID string
				if errS := stockRows.Scan(&sID); errS == nil && sID != "" {
					samples = append(samples, sID)
				}
			}
			stockRows.Close()
			r.AvailableAssetSamples = samples
			r.AvailableUnitsCount = len(samples)
		}

		recs = append(recs, r)
	}

	// Fallback to active inventory if no borrow history exists yet for this query
	if len(recs) == 0 && (searchQuery != "" || category != "" || location != "") {
		fallbackQuery := `
			SELECT 
				MAX(a.name) AS asset_name,
				MAX(COALESCE(a.category, '')) AS category,
				MAX(COALESCE(a.model_type, '')) AS model_type,
				MAX(COALESCE(a.brand, '')) AS brand,
				0 AS borrow_count,
				0 AS distinct_borrowers,
				14 AS avg_duration_days,
				'' AS last_borrowed_date,
				COUNT(a.id) AS available_count
			FROM public.assets a
			WHERE LOWER(COALESCE(a.status, 'available')) IN ('available', 'active')
		`
		fbArgs := []any{}
		fbIdx := 1
		if userCompany != "" {
			fallbackQuery += fmt.Sprintf(` AND (
				LOWER(TRIM(a.perusahaan)) = LOWER(TRIM($%d))
				OR EXISTS (
					SELECT 1 FROM public.perusahaan p
					WHERE (LOWER(TRIM(p.nama_perusahaan)) = LOWER(TRIM($%d)) OR p.id_perusahaan::text = LOWER(TRIM($%d)))
					  AND (a.perusahaan = p.id_perusahaan::text OR LOWER(TRIM(a.perusahaan)) = LOWER(TRIM(p.nama_perusahaan)))
				)
			)`, fbIdx, fbIdx, fbIdx)
			fbArgs = append(fbArgs, userCompany)
			fbIdx++
		}
		if searchQuery != "" {
			fallbackQuery += fmt.Sprintf(` AND (
				LOWER(a.name) ILIKE '%%' || LOWER($%d) || '%%'
				OR LOWER(a.category) ILIKE '%%' || LOWER($%d) || '%%'
				OR LOWER(a.model_type) ILIKE '%%' || LOWER($%d) || '%%'
				OR LOWER(a.location) ILIKE '%%' || LOWER($%d) || '%%'
			)`, fbIdx, fbIdx, fbIdx, fbIdx)
			fbArgs = append(fbArgs, searchQuery)
			fbIdx++
		}
		fallbackQuery += fmt.Sprintf(`
			GROUP BY LOWER(TRIM(a.name))
			ORDER BY available_count DESC
			LIMIT $%d
		`, fbIdx)
		fbArgs = append(fbArgs, limit)

		fbRows, fbErr := DB.Query(ctx, fallbackQuery, fbArgs...)
		if fbErr == nil {
			defer fbRows.Close()
			for fbRows.Next() {
				var r BorrowHistoryRecommendation
				var availCount int
				if errFb := fbRows.Scan(
					&r.AssetName, &r.Category, &r.ModelType, &r.Brand,
					&r.BorrowCount, &r.DistinctBorrowers, &r.AvgDurationDays, &r.LastBorrowedDate,
					&availCount,
				); errFb == nil {
					r.RecommendationReason = fmt.Sprintf("Belum ada riwayat peminjaman untuk kategori ini. Direkomendasikan berdasarkan ketersediaan unit aktif di inventaris (%d unit tersedia)", availCount)
					r.AvailableUnitsCount = availCount
					recs = append(recs, r)
				}
			}
		}
	}

	if recs == nil {
		recs = []BorrowHistoryRecommendation{}
	}

	return c.JSON(fiber.Map{
		"recommendations": recs,
		"total":           len(recs),
		"search_criteria": fiber.Map{
			"query":    searchQuery,
			"category": category,
			"location": location,
			"company":  userCompany,
		},
	})
}

// GetBorrowTransaction handles GET /api/borrow/:id
func GetBorrowTransaction(c *fiber.Ctx) error {
	idParam := c.Params("id")
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	var trx BorrowApprovalTransaction
	err := DB.QueryRow(ctx, `
		SELECT id, transaction_code, borrower_id, borrower_name, 
		       COALESCE(manager_id, ''), manager_name, group_name, 
		       request_date, status
		FROM public.borrow_transactions
		WHERE id::text = $1 OR transaction_code = $1
	`, idParam).Scan(
		&trx.ID, &trx.TransactionCode, &trx.BorrowerID, &trx.BorrowerName,
		&trx.ManagerID, &trx.ManagerName, &trx.GroupName,
		&trx.RequestDate, &trx.Status,
	)
	if err != nil {
		return c.Status(404).JSON(fiber.Map{"error": "Transaction not found"})
	}

	// Tenant boundary check: transaction belongs to userCompany if u.company == userCompany OR trx.GroupName == userCompany
	reqCompany := strings.TrimSpace(c.Get("X-Company"))
	if _, uComp := resolveUserContext(c); uComp != "" {
		reqCompany = uComp
	}
	if reqCompany != "" {
		var borrowerCompany string
		_ = DB.QueryRow(ctx, `SELECT COALESCE(company, '') FROM public.users WHERE id::text = $1 OR LOWER(username) = LOWER($2) LIMIT 1`, trx.BorrowerID, trx.BorrowerName).Scan(&borrowerCompany)

		matches := false
		if borrowerCompany != "" && strings.EqualFold(borrowerCompany, reqCompany) {
			matches = true
		} else if trx.GroupName != "" && strings.EqualFold(trx.GroupName, reqCompany) {
			matches = true
		}

		if !matches && (borrowerCompany != "" || trx.GroupName != "") {
			return c.Status(403).JSON(fiber.Map{"error": "Access denied to transaction from another company"})
		}
	}

	// Role scoping: non-admin can only access their own transaction
	role := strings.ToLower(strings.TrimSpace(c.Query("role")))
	if role == "" {
		role = strings.ToLower(strings.TrimSpace(c.Get("X-Role")))
	}
	borrowerID := strings.TrimSpace(c.Query("borrower_id"))
	if borrowerID == "" {
		borrowerID = strings.TrimSpace(c.Get("X-User-ID"))
	}
	if role != "admin" && borrowerID != "" {
		if trx.BorrowerID != borrowerID && !strings.EqualFold(trx.BorrowerName, borrowerID) {
			return c.Status(403).JSON(fiber.Map{"error": "Access denied to this transaction"})
		}
	}

	rows, err := DB.Query(ctx, `
		SELECT i.id, i.transaction_id, i.asset_id, COALESCE(a.name, ''), 
		       COALESCE(a.brand, ''), COALESCE(a.model_type, ''), COALESCE(a.category, ''),
		       i.duration_days, i.approved_duration_days, i.note, i.is_approved, i.status
		FROM public.borrow_items i
		LEFT JOIN public.assets a ON i.asset_id = a.asset_id
		WHERE i.transaction_id = $1
	`, trx.ID)
	if err == nil {
		defer rows.Close()
		for rows.Next() {
			var itm BorrowApprovalItem
			_ = rows.Scan(
				&itm.ID, &itm.TransactionID, &itm.AssetID, &itm.AssetName,
				&itm.Brand, &itm.ModelType, &itm.Category,
				&itm.DurationDays, &itm.ApprovedDurationDays, &itm.Note, &itm.IsApproved, &itm.Status,
			)
			trx.Items = append(trx.Items, itm)
		}
	}
	trx.ItemCount = len(trx.Items)

	return c.JSON(trx)
}

// CheckBorrowAnomalies handles GET /api/borrow/:id/anomalies
func CheckBorrowAnomalies(c *fiber.Ctx) error {
	idParam := c.Params("id")
	ctx, cancel := context.WithTimeout(context.Background(), 40*time.Second)
	defer cancel()

	// 1. Get Transaction Info
	var trx BorrowApprovalTransaction
	err := DB.QueryRow(ctx, `
		SELECT id, transaction_code, borrower_id, borrower_name, group_name, request_date
		FROM public.borrow_transactions
		WHERE id::text = $1 OR transaction_code = $1
	`, idParam).Scan(
		&trx.ID, &trx.TransactionCode, &trx.BorrowerID, &trx.BorrowerName, &trx.GroupName, &trx.RequestDate,
	)
	if err != nil {
		return c.Status(404).JSON(fiber.Map{"error": "Transaction not found"})
	}

	// 2. Fetch Items
	rows, err := DB.Query(ctx, `
		SELECT i.id, i.asset_id, COALESCE(a.name, ''), COALESCE(a.category, ''), i.duration_days
		FROM public.borrow_items i
		LEFT JOIN public.assets a ON i.asset_id = a.asset_id
		WHERE i.transaction_id = $1
	`, trx.ID)
	if err != nil {
		return c.Status(500).JSON(fiber.Map{"error": err.Error()})
	}
	defer rows.Close()

	type itemDetail struct {
		AssetID      string
		AssetName    string
		Category     string
		DurationDays int
	}
	var items []itemDetail
	for rows.Next() {
		var itm itemDetail
		var dummyID string
		_ = rows.Scan(&dummyID, &itm.AssetID, &itm.AssetName, &itm.Category, &itm.DurationDays)
		items = append(items, itm)
	}

	// 3. Compute 7 Signals using tenant-specific thresholds from database
	tenantName := strings.TrimSpace(trx.GroupName)
	if tenantName == "" {
		tenantName = ResolveTenantCompany(c)
	}
	cfg := GetTenantThresholds(ctx, tenantName)

	// Optional query overrides per request (e.g. ?max_duration_days=30&max_active_loans=5)
	if qDur := c.Query("max_duration_days"); qDur != "" {
		if v, err := strconv.Atoi(qDur); err == nil && v > 0 {
			cfg.MaxDurationDays = v
		}
	}
	if qAct := c.Query("max_active_loans"); qAct != "" {
		if v, err := strconv.Atoi(qAct); err == nil && v > 0 {
			cfg.MaxActiveLoans = v
		}
	}
	if qLate := c.Query("max_late_returns"); qLate != "" {
		if v, err := strconv.Atoi(qLate); err == nil && v > 0 {
			cfg.MaxLateReturns = v
		}
	}
	if qExt := c.Query("max_extensions"); qExt != "" {
		if v, err := strconv.Atoi(qExt); err == nil && v > 0 {
			cfg.MaxExtensions = v
		}
	}
	if qCount := c.Query("max_asset_count"); qCount != "" {
		if v, err := strconv.Atoi(qCount); err == nil && v > 0 {
			cfg.MaxAssetCount = v
		}
	}
	if qAudit := c.Query("audit_window_days"); qAudit != "" {
		if v, err := strconv.Atoi(qAudit); err == nil && v > 0 {
			cfg.AuditWindowDays = v
		}
	}
	if qRep := c.Query("repeat_borrow_cycles"); qRep != "" {
		if v, err := strconv.Atoi(qRep); err == nil && v > 0 {
			cfg.RepeatBorrowCycles = v
		}
	}
	if qMin := c.Query("min_signals_for_review"); qMin != "" {
		if v, err := strconv.Atoi(qMin); err == nil && v > 0 {
			cfg.MinSignalsForReview = v
		}
	}

	var triggeredSignals []string
	var allSignals []AnomalySignal

	// Sinyal 1: Durasi tiap aset vs kebiasaan kategori (Ambang: > cfg.MaxDurationDays)
	s1Triggered := false
	s1Desc := "Durasi request sesuai batas normal kebiasaan kategori aset."
	for _, it := range items {
		if it.DurationDays > cfg.MaxDurationDays {
			s1Triggered = true
			s1Desc = fmt.Sprintf("Durasi pinjam (%d hari) melampaui batas kebiasaan kategori %s (> %d hari).", it.DurationDays, it.Category, cfg.MaxDurationDays)
			triggeredSignals = append(triggeredSignals, s1Desc)
			break
		}
	}
	allSignals = append(allSignals, AnomalySignal{
		ID:          1,
		Name:        "Durasi tiap aset vs kebiasaan kategori",
		Triggered:   s1Triggered,
		Description: s1Desc,
	})

	// Sinyal 2: Pinjaman aktif peminjam (Group ini & Total)
	var activeLoansGroup, activeLoansTotal int
	_ = DB.QueryRow(ctx, `
		SELECT COUNT(DISTINCT t.id)
		FROM public.borrow_transactions t
		WHERE t.borrower_id = $1 AND t.status = 'active' AND t.group_name = $2
	`, trx.BorrowerID, trx.GroupName).Scan(&activeLoansGroup)

	_ = DB.QueryRow(ctx, `
		SELECT COUNT(DISTINCT t.id)
		FROM public.borrow_transactions t
		WHERE t.borrower_id = $1 AND t.status = 'active'
	`, trx.BorrowerID).Scan(&activeLoansTotal)

	s2Triggered := activeLoansTotal >= cfg.MaxActiveLoans
	s2Desc := fmt.Sprintf("Peminjam saat ini memegang %d pinjaman aktif.", activeLoansTotal)
	if s2Triggered {
		s2Desc = fmt.Sprintf("Peminjam memiliki %d pinjaman aktif sekaligus (ambang batas >= %d).", activeLoansTotal, cfg.MaxActiveLoans)
		triggeredSignals = append(triggeredSignals, s2Desc)
	}
	allSignals = append(allSignals, AnomalySignal{
		ID:          2,
		Name:        "Pinjaman aktif peminjam",
		Triggered:   s2Triggered,
		Description: s2Desc,
	})

	// Sinyal 3: Telat kembali (6 bulan terakhir)
	var lateReturnsGroup, lateReturnsTotal int
	_ = DB.QueryRow(ctx, `
		SELECT COUNT(DISTINCT t.id)
		FROM public.borrow_transactions t
		JOIN public.borrow_items i ON t.id = i.transaction_id
		WHERE t.borrower_id = $1 AND t.group_name = $2
		  AND i.returned_at > i.due_date
		  AND i.returned_at >= NOW() - INTERVAL '6 months'
	`, trx.BorrowerID, trx.GroupName).Scan(&lateReturnsGroup)

	_ = DB.QueryRow(ctx, `
		SELECT COUNT(DISTINCT t.id)
		FROM public.borrow_transactions t
		JOIN public.borrow_items i ON t.id = i.transaction_id
		WHERE t.borrower_id = $1
		  AND i.returned_at > i.due_date
		  AND i.returned_at >= NOW() - INTERVAL '6 months'
	`, trx.BorrowerID).Scan(&lateReturnsTotal)

	s3Triggered := lateReturnsTotal >= cfg.MaxLateReturns
	s3Desc := fmt.Sprintf("Keterlambatan pengembalian: %d kali dalam 6 bulan.", lateReturnsTotal)
	if s3Triggered {
		s3Desc = fmt.Sprintf("Peminjam tercatat %d kali terlambat mengembalikan aset dalam 6 bulan terakhir (ambang batas >= %d).", lateReturnsTotal, cfg.MaxLateReturns)
		triggeredSignals = append(triggeredSignals, s3Desc)
	}
	allSignals = append(allSignals, AnomalySignal{
		ID:          3,
		Name:        "Telat kembali (6 bulan terakhir)",
		Triggered:   s3Triggered,
		Description: s3Desc,
	})

	// Sinyal 4: Sering perpanjangan (6 bulan terakhir)
	var extGroup, extTotal int
	_ = DB.QueryRow(ctx, `
		SELECT COUNT(e.id)
		FROM public.borrow_extensions e
		JOIN public.borrow_transactions t ON e.transaction_id = t.id
		WHERE e.borrower_id = $1 AND t.group_name = $2
		  AND e.request_date >= NOW() - INTERVAL '6 months'
	`, trx.BorrowerID, trx.GroupName).Scan(&extGroup)

	_ = DB.QueryRow(ctx, `
		SELECT COUNT(id)
		FROM public.borrow_extensions
		WHERE borrower_id = $1 AND request_date >= NOW() - INTERVAL '6 months'
	`, trx.BorrowerID).Scan(&extTotal)

	s4Triggered := extTotal >= cfg.MaxExtensions
	s4Desc := fmt.Sprintf("Pengajuan perpanjangan: %d kali dalam 6 bulan.", extTotal)
	if s4Triggered {
		s4Desc = fmt.Sprintf("Peminjam telah mengajukan perpanjangan durasi %d kali dalam 6 bulan terakhir (ambang batas >= %d).", extTotal, cfg.MaxExtensions)
		triggeredSignals = append(triggeredSignals, s4Desc)
	}
	allSignals = append(allSignals, AnomalySignal{
		ID:          4,
		Name:        "Sering perpanjangan",
		Triggered:   s4Triggered,
		Description: s4Desc,
	})

	// Sinyal 5: Jumlah aset per request (> cfg.MaxAssetCount aset)
	s5Triggered := len(items) > cfg.MaxAssetCount
	s5Desc := fmt.Sprintf("Jumlah aset dalam permohonan: %d aset.", len(items))
	if s5Triggered {
		s5Desc = fmt.Sprintf("Jumlah aset yang diajukan (%d aset) melebihi batas kebiasaan transaksi (> %d aset).", len(items), cfg.MaxAssetCount)
		triggeredSignals = append(triggeredSignals, s5Desc)
	}
	allSignals = append(allSignals, AnomalySignal{
		ID:          5,
		Name:        "Jumlah aset per request vs kebiasaan",
		Triggered:   s5Triggered,
		Description: s5Desc,
	})

	// Sinyal 6: Menghindari jadwal Audit (rentang cfg.AuditWindowDays hari sebelum jadwal audit mulai)
	s6Triggered := false
	s6Desc := fmt.Sprintf("Tidak terdeteksi jadwal audit dalam rentang %d hari ke depan.", cfg.AuditWindowDays)
	var auditCategory string
	var auditStartDate time.Time
	auditIntervalStr := fmt.Sprintf("%d days", cfg.AuditWindowDays)
	errAudit := DB.QueryRow(ctx, `
		SELECT category, TO_DATE(start, 'YYYY-MM-DD')
		FROM public.schedule
		WHERE group_name = $1
		  AND TO_DATE(start, 'YYYY-MM-DD') >= $2::date
		  AND TO_DATE(start, 'YYYY-MM-DD') <= ($2::date + $3::interval)
		ORDER BY TO_DATE(start, 'YYYY-MM-DD') ASC
		LIMIT 1
	`, trx.GroupName, trx.RequestDate, auditIntervalStr).Scan(&auditCategory, &auditStartDate)

	if errAudit == nil {
		s6Triggered = true
		diffDays := int(auditStartDate.Sub(trx.RequestDate).Hours() / 24)
		if diffDays < 0 {
			diffDays = 0
		}
		s6Desc = fmt.Sprintf("Permohonan diajukan mepet (%d hari sebelum) jadwal %s pada %s.", diffDays, auditCategory, auditStartDate.Format("02 Jan 2006"))
		triggeredSignals = append(triggeredSignals, s6Desc)
	}
	allSignals = append(allSignals, AnomalySignal{
		ID:          6,
		Name:        "Menghindari jadwal Audit",
		Triggered:   s6Triggered,
		Description: s6Desc,
	})

	// Sinyal 7: Pinjam ulang berturut-turut (aset sama, orang sama, cycleCount >= cfg.RepeatBorrowCycles)
	s7Triggered := false
	s7Desc := "Tidak ada riwayat perputaran pinjam-kembalikan berulang jarak dekat."
	for _, it := range items {
		var cycleCount int
		_ = DB.QueryRow(ctx, `
			SELECT COUNT(DISTINCT t.id)
			FROM public.borrow_transactions t
			JOIN public.borrow_items i ON t.id = i.transaction_id
			WHERE t.borrower_id = $1 AND i.asset_id = $2
			  AND t.status = 'completed'
			  AND i.returned_at >= NOW() - INTERVAL '6 months'
		`, trx.BorrowerID, it.AssetID).Scan(&cycleCount)

		if cycleCount >= cfg.RepeatBorrowCycles {
			s7Triggered = true
			s7Desc = fmt.Sprintf("Aset '%s' memiliki siklus berulang pinjam-kembalikan-pinjam lagi oleh peminjam ini (%d kali dalam 6 bulan, ambang batas >= %d).", it.AssetName, cycleCount, cfg.RepeatBorrowCycles)
			triggeredSignals = append(triggeredSignals, s7Desc)
			break
		}
	}
	allSignals = append(allSignals, AnomalySignal{
		ID:          7,
		Name:        "Pinjam ulang berturut-turut",
		Triggered:   s7Triggered,
		Description: s7Desc,
	})

	// 4. Build Borrower Context Summary
	borrowerContext := []AnomalyContextItem{
		{
			Metric:   "Pinjaman aktif",
			GroupVal: activeLoansGroup,
			TotalVal: activeLoansTotal,
			Status:   statusLabel(s2Triggered),
		},
		{
			Metric:   "Telat kembali (6 bulan terakhir)",
			GroupVal: lateReturnsGroup,
			TotalVal: lateReturnsTotal,
			Status:   statusLabel(s3Triggered),
		},
		{
			Metric:   "Jumlah pengajuan perpanjangan (6 bulan terakhir)",
			GroupVal: extGroup,
			TotalVal: extTotal,
			Status:   statusLabel(s4Triggered),
		},
	}

	signalsCount := len(triggeredSignals)
	reviewRecommended := signalsCount >= cfg.MinSignalsForReview

	// 5. Generate Narrative (AI Synthesizer or Empty/Error without placeholder fallback)
	narrative := ""
	errorMessage := ""
	isAI := false
	if signalsCount > 0 {
		log.Printf("[borrow_anomaly] Requesting AI narrative from eiai_go for %s (%d signals)...", trx.BorrowerName, signalsCount)
		aiNarrative, errAI := synthesizeNarrativeWithAI(trx.BorrowerName, trx.GroupName, triggeredSignals)
		if errAI != nil {
			log.Printf("[borrow_anomaly] AI narrative error: %v", errAI)
			errorMessage = errAI.Error()
		} else {
			log.Printf("[borrow_anomaly] Received AI narrative: %s", aiNarrative)
			narrative = aiNarrative
			isAI = true
		}
	}

	response := AnomalyReportResponse{
		DataAsOf:          time.Now().Format("02 Jan 2006 15:04:05 WIB"),
		TransactionCode:   trx.TransactionCode,
		BorrowerName:      trx.BorrowerName,
		GroupName:         trx.GroupName,
		BorrowerContext:   borrowerContext,
		RequestContext:    allSignals,
		SignalsCount:      signalsCount,
		ReviewRecommended: reviewRecommended,
		Thresholds:        &cfg,
		Narrative:         narrative,
		ErrorMessage:      errorMessage,
		IsAIGenerated:     isAI,
	}

	return c.JSON(response)
}

func statusLabel(triggered bool) string {
	if triggered {
		return "menonjol"
	}
	return "normal"
}

// synthesizeNarrativeWithAI calls eiai_go service to synthesize a flowing narrative
func synthesizeNarrativeWithAI(borrowerName, groupName string, signals []string) (string, error) {
	eiaiURL := os.Getenv("EIAI_URL")
	if eiaiURL == "" {
		eiaiURL = "http://127.0.0.1:8000"
	}
	baseURL := strings.TrimRight(eiaiURL, "/")
	if strings.HasSuffix(baseURL, "/rag") {
		baseURL = strings.TrimSuffix(baseURL, "/rag")
	}

	payload := map[string]interface{}{
		"borrower_name": borrowerName,
		"group_name":    groupName,
		"signals":       signals,
	}

	bodyBytes, _ := json.Marshal(payload)
	req, err := http.NewRequest("POST", baseURL+"/anomaly/narrative", bytes.NewBuffer(bodyBytes))
	if err != nil {
		return "", err
	}
	req.Header.Set("Content-Type", "application/json")

	client := &http.Client{Timeout: 35 * time.Second}
	resp, err := client.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		respBody, _ := io.ReadAll(resp.Body)
		return "", fmt.Errorf("EIAI error %d: %s", resp.StatusCode, string(respBody))
	}

	var res struct {
		Narrative string `json:"narrative"`
		Error     string `json:"error"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&res); err != nil {
		return "", err
	}
	if res.Error != "" {
		return "", fmt.Errorf("%s", res.Error)
	}

	return strings.TrimSpace(res.Narrative), nil
}

// ApproveBorrowTransaction handles POST /api/borrow/:id/approve
func ApproveBorrowTransaction(c *fiber.Ctx) error {
	idParam := c.Params("id")
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	type ItemDecision struct {
		ID                   string  `json:"id"`
		ApprovedDurationDays *int    `json:"approved_duration_days"`
		Note                 *string `json:"note"`
		IsApproved           *bool   `json:"is_approved"`
	}

	var payload struct {
		Decision string         `json:"decision"` // "approve" or "reject"
		Items    []ItemDecision `json:"items"`
	}

	if err := c.BodyParser(&payload); err != nil {
		return c.Status(400).JSON(fiber.Map{"error": "Invalid request body"})
	}

	for _, itm := range payload.Items {
		itemStatus := "approved"
		if itm.IsApproved != nil && !*itm.IsApproved {
			itemStatus = "rejected"
		}
		_, _ = DB.Exec(ctx, `
			UPDATE public.borrow_items
			SET approved_duration_days = $1, note = $2, is_approved = $3, status = $4
			WHERE id::text = $5
		`, itm.ApprovedDurationDays, itm.Note, itm.IsApproved, itemStatus, itm.ID)
	}

	if payload.Decision == "reject" {
		// Ditolak: Hapus dari borrow_items dan borrow_transactions agar tidak memenuhi halaman
		var trxUUID string
		_ = DB.QueryRow(ctx, `SELECT id FROM public.borrow_transactions WHERE id::text = $1 OR transaction_code = $1 LIMIT 1`, idParam).Scan(&trxUUID)
		if trxUUID != "" {
			_, _ = DB.Exec(ctx, `DELETE FROM public.borrow_items WHERE transaction_id = $1`, trxUUID)
			_, _ = DB.Exec(ctx, `DELETE FROM public.borrow_transactions WHERE id = $1`, trxUUID)
		} else {
			_, _ = DB.Exec(ctx, `DELETE FROM public.borrow_transactions WHERE id::text = $1 OR transaction_code = $1`, idParam)
		}
		return c.JSON(fiber.Map{"message": "Transaksi berhasil ditolak dan dihapus", "status": "deleted"})
	}

	overallStatus := "approved"
	_, err := DB.Exec(ctx, `
		UPDATE public.borrow_transactions
		SET status = $1
		WHERE id::text = $2 OR transaction_code = $2
	`, overallStatus, idParam)
	if err != nil {
		return c.Status(500).JSON(fiber.Map{"error": err.Error()})
	}

	// Update asset status to 'borrowed' for approved items in public.assets
	var trxUUID string
	_ = DB.QueryRow(ctx, `SELECT id FROM public.borrow_transactions WHERE id::text = $1 OR transaction_code = $1 LIMIT 1`, idParam).Scan(&trxUUID)
	if trxUUID != "" {
		_, _ = DB.Exec(ctx, `
			UPDATE public.assets
			SET status = 'borrowed'
			WHERE asset_id IN (
				SELECT asset_id FROM public.borrow_items
				WHERE transaction_id = $1 AND COALESCE(status, 'approved') != 'rejected'
			)
		`, trxUUID)
	}

	return c.JSON(fiber.Map{"message": "Transaction approval processed successfully", "status": overallStatus})
}

// ResolveUserByBorrowerName searches public.users to get the exact users.id (LIMIT 1).
func ResolveUserByBorrowerName(ctx context.Context, name string) (userID, username, company string, found bool) {
	name = strings.TrimSpace(name)
	if name == "" {
		return "", "", "", false
	}

	// 1. Direct exact match on username or email in public.users
	err := DB.QueryRow(ctx, `
		SELECT id, username, COALESCE(company, '') 
		FROM public.users 
		WHERE LOWER(TRIM(username)) = LOWER(TRIM($1)) OR LOWER(TRIM(email)) = LOWER(TRIM($1))
		LIMIT 1
	`, name).Scan(&userID, &username, &company)
	if err == nil && userID != "" {
		return userID, username, company, true
	}

	// 2. Token-based matching: split string into words (e.g. "sasori dan tordalk" -> "sasori", "tordalk")
	tokens := strings.FieldsFunc(name, func(r rune) bool {
		return r == ' ' || r == ',' || r == ';' || r == '/' || r == '\\' || r == '&' || r == '-' || r == '_'
	})
	noiseWords := map[string]bool{
		"dan": true, "and": true, "atau": true, "or": true, "untuk": true, "for": true,
		"si": true, "ke": true, "di": true, "dari": true, "with": true, "dengan": true,
		"yg": true, "yang": true, "pada": true,
	}
	for _, tok := range tokens {
		tokClean := strings.ToLower(strings.Trim(tok, " \t\r\n,.;:!?'\"()[]{}"))
		if len(tokClean) < 2 || noiseWords[tokClean] {
			continue
		}
		err = DB.QueryRow(ctx, `
			SELECT id, username, COALESCE(company, '') 
			FROM public.users 
			WHERE LOWER(TRIM(username)) = LOWER(TRIM($1)) OR LOWER(TRIM(email)) = LOWER(TRIM($1))
			LIMIT 1
		`, tokClean).Scan(&userID, &username, &company)
		if err == nil && userID != "" {
			return userID, username, company, true
		}
	}

	// 3. Reverse substring match ($1 ILIKE '%' || username || '%') and substring match
	err = DB.QueryRow(ctx, `
		SELECT id, username, COALESCE(company, '') 
		FROM public.users 
		WHERE $1 ILIKE '%' || username || '%' OR username ILIKE '%' || $1 || '%'
		ORDER BY 
			CASE 
				WHEN LOWER(TRIM(username)) = LOWER(TRIM($1)) THEN 1
				WHEN $1 ILIKE '%' || username || '%' THEN 2
				ELSE 3
			END, 
			LENGTH(username) DESC
		LIMIT 1
	`, name).Scan(&userID, &username, &company)
	if err == nil && userID != "" {
		return userID, username, company, true
	}

	// 4. Token substring in public.users
	for _, tok := range tokens {
		tokClean := strings.ToLower(strings.Trim(tok, " \t\r\n,.;:!?'\"()[]{}"))
		if len(tokClean) < 3 || noiseWords[tokClean] {
			continue
		}
		err = DB.QueryRow(ctx, `
			SELECT id, username, COALESCE(company, '') 
			FROM public.users 
			WHERE username ILIKE '%' || $1 || '%'
			ORDER BY LENGTH(username) ASC
			LIMIT 1
		`, tokClean).Scan(&userID, &username, &company)
		if err == nil && userID != "" {
			return userID, username, company, true
		}
	}

	// 5. Try legacy public."user" table
	var legacyUID any
	var legacyName, legacyPerusahaan string
	err = DB.QueryRow(ctx, `
		SELECT user_id, COALESCE(name, ''), COALESCE(perusahaan, '') 
		FROM public."user" 
		WHERE $1 ILIKE '%' || name || '%' OR name ILIKE '%' || $1 || '%'
		ORDER BY LENGTH(name) DESC
		LIMIT 1
	`, name).Scan(&legacyUID, &legacyName, &legacyPerusahaan)
	if err == nil && legacyUID != nil {
		return fmt.Sprintf("%v", legacyUID), legacyName, legacyPerusahaan, true
	}

	// 6. Try previous borrow_transactions where borrower_id is a UUID or exists in public.users
	var priorID, priorName, priorGroup string
	err = DB.QueryRow(ctx, `
		SELECT b.borrower_id, b.borrower_name, COALESCE(b.group_name, '')
		FROM public.borrow_transactions b
		WHERE (b.borrower_name ILIKE '%' || $1 || '%' OR $1 ILIKE '%' || b.borrower_name || '%')
		  AND b.borrower_id IS NOT NULL 
		  AND b.borrower_id != ''
		  AND b.borrower_id != b.borrower_name
		ORDER BY b.created_at DESC
		LIMIT 1
	`, name).Scan(&priorID, &priorName, &priorGroup)
	if err == nil && priorID != "" {
		return priorID, priorName, priorGroup, true
	}

	// 7. Fallback to first registered user in public.users so borrower_id is ALWAYS a valid users.id
	var defaultID, defaultUsername, defaultCompany string
	err = DB.QueryRow(ctx, `
		SELECT id, username, COALESCE(company, '') 
		FROM public.users 
		ORDER BY created_at ASC 
		LIMIT 1
	`).Scan(&defaultID, &defaultUsername, &defaultCompany)
	if err == nil && defaultID != "" {
		log.Printf("[ResolveUserByBorrowerName] No direct user match for '%s', resolved fallback users.id=%s (username=%s)", name, defaultID, defaultUsername)
		return defaultID, name, defaultCompany, false
	}

	return "", name, "", false
}

