// UpdateHoldBorrowPayload represents fields that can be edited in a held borrow request
type UpdateHoldBorrowPayload struct {
	BorrowerName string           `json:"borrower_name"`
	BorrowerID   string           `json:"borrower_id"`
	GroupName    string           `json:"group_name"`
	Notes        string           `json:"notes"`
	Items        []HoldBorrowItem `json:"items"`
}

// UpdateHoldBorrow updates editable fields of a held borrow request before confirmation
func UpdateHoldBorrow(c *fiber.Ctx) error {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	id := strings.TrimSpace(c.Params("id"))
	if id == "" {
		return c.Status(400).JSON(fiber.Map{"error": "ID or hold_code is required"})
	}

	var payload UpdateHoldBorrowPayload
	if err := c.BodyParser(&payload); err != nil {
		return c.Status(400).JSON(fiber.Map{"error": "Format request tidak valid: " + err.Error()})
	}

	// 1. Fetch current record
	var currentStatus, currentBorrowerID, currentBorrowerName, currentGroupName, currentNotes string
	var currentItemsRaw []byte
	err := DB.QueryRow(ctx, `
		SELECT status, borrower_id, borrower_name, group_name, notes, items
		FROM public.hold_borrow
		WHERE id::text = $1 OR hold_code = $1
		LIMIT 1
	`, id).Scan(&currentStatus, &currentBorrowerID, &currentBorrowerName, &currentGroupName, &currentNotes, &currentItemsRaw)

	if err != nil {
		return c.Status(404).JSON(fiber.Map{"error": "Permohonan hold borrow tidak ditemukan"})
	}

	if currentStatus != "held" {
		return c.Status(400).JSON(fiber.Map{"error": fmt.Sprintf("Permohonan hold tidak dapat diedit karena statusnya sudah '%s'", currentStatus)})
	}

	// 2. Resolve updated fields
	newBorrowerName := strings.TrimSpace(payload.BorrowerName)
	if newBorrowerName == "" {
		newBorrowerName = currentBorrowerName
	}

	newBorrowerID := strings.TrimSpace(payload.BorrowerID)
	// If borrower name changed or borrower ID is empty, resolve user ID
	if newBorrowerName != currentBorrowerName || newBorrowerID == "" {
		uID, uName, uCompany, found := ResolveUserByBorrowerName(ctx, newBorrowerName)
		if uID != "" {
			newBorrowerID = uID
			if found && uName != "" {
				newBorrowerName = uName
			}
			if uCompany != "" && strings.TrimSpace(payload.GroupName) == "" {
				payload.GroupName = uCompany
			}
		} else if newBorrowerID == "" {
			newBorrowerID = currentBorrowerID
		}
	}

	newGroupName := strings.TrimSpace(payload.GroupName)
	if newGroupName == "" {
		newGroupName = currentGroupName
	}

	newNotes := strings.TrimSpace(payload.Notes)
	if newNotes == "" {
		newNotes = currentNotes
	}

	var newItems []HoldBorrowItem
	if payload.Items != nil {
		if len(payload.Items) == 0 {
			return c.Status(400).JSON(fiber.Map{"error": "Permohonan hold minimal harus memiliki 1 aset"})
		}
		for i := range payload.Items {
			it := payload.Items[i]
			it.AssetID = strings.TrimSpace(it.AssetID)
			if it.AssetID == "" {
				continue
			}
			if it.DurationDays <= 0 {
				it.DurationDays = 14
			}
			// Enrich asset name and category if missing
			if it.AssetName == "" || it.Category == "" {
				var aName, aCat string
				_ = DB.QueryRow(ctx, `SELECT name, category FROM public.assets WHERE asset_id ILIKE $1 LIMIT 1`, it.AssetID).Scan(&aName, &aCat)
				if it.AssetName == "" && aName != "" {
					it.AssetName = aName
				}
				if it.Category == "" && aCat != "" {
					it.Category = aCat
				}
			}
			newItems = append(newItems, it)
		}
		if len(newItems) == 0 {
			return c.Status(400).JSON(fiber.Map{"error": "Minimal 1 aset yang valid harus dicantumkan"})
		}
	} else {
		if len(currentItemsRaw) > 0 {
			_ = json.Unmarshal(currentItemsRaw, &newItems)
		}
	}

	newItemsJSON, err := json.Marshal(newItems)
	if err != nil {
		newItemsJSON = []byte("[]")
	}

	// 3. Update DB
	var updatedRecord HoldBorrowRecord
	var updatedItemsRaw []byte
	err = DB.QueryRow(ctx, `
		UPDATE public.hold_borrow
		SET borrower_id = $1,
		    borrower_name = $2,
		    group_name = $3,
		    notes = $4,
		    items = $5,
		    updated_at = NOW()
		WHERE id::text = $6 OR hold_code = $6
		RETURNING id, hold_code, borrower_id, borrower_name, manager_id, manager_name, group_name, items, status, COALESCE(notes, ''), created_at, updated_at
	`, newBorrowerID, newBorrowerName, newGroupName, newNotes, newItemsJSON, id).Scan(
		&updatedRecord.ID, &updatedRecord.HoldCode, &updatedRecord.BorrowerID, &updatedRecord.BorrowerName,
		&updatedRecord.ManagerID, &updatedRecord.ManagerName, &updatedRecord.GroupName, &updatedItemsRaw,
		&updatedRecord.Status, &updatedRecord.Notes, &updatedRecord.CreatedAt, &updatedRecord.UpdatedAt,
	)

	if err != nil {
		return c.Status(500).JSON(fiber.Map{"error": "Gagal memperbarui permohonan hold: " + err.Error()})
	}

	if len(updatedItemsRaw) > 0 {
		_ = json.Unmarshal(updatedItemsRaw, &updatedRecord.Items)
	}

	return c.JSON(fiber.Map{
		"message": "Data permohonan hold peminjaman berhasil diperbarui",
		"data":    updatedRecord,
	})
}

// SubmitHoldBorrow manually submits a held borrow record into official borrow_transactions
func SubmitHoldBorrow(c *fiber.Ctx) error {
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	id := strings.TrimSpace(c.Params("id"))
	if id == "" {
		return c.Status(400).JSON(fiber.Map{"error": "ID or hold_code is required"})
	}

	var r HoldBorrowRecord
	var itemsRaw []byte
	err := DB.QueryRow(ctx, `
		SELECT id, hold_code, borrower_id, borrower_name, manager_id, manager_name, group_name, items, status, COALESCE(notes, ''), created_at, updated_at
		FROM public.hold_borrow
		WHERE id::text = $1 OR hold_code = $1
		LIMIT 1
	`, id).Scan(&r.ID, &r.HoldCode, &r.BorrowerID, &r.BorrowerName, &r.ManagerID, &r.ManagerName, &r.GroupName, &itemsRaw, &r.Status, &r.Notes, &r.CreatedAt, &r.UpdatedAt)

	if err != nil {
		return c.Status(404).JSON(fiber.Map{"error": "Permohonan hold borrow tidak ditemukan"})
	}

	if r.Status != "held" {
		return c.Status(400).JSON(fiber.Map{"error": fmt.Sprintf("Permohonan hold ini tidak dapat di-submit karena statusnya '%s'", r.Status)})
	}

	if len(itemsRaw) > 0 {
		_ = json.Unmarshal(itemsRaw, &r.Items)
	}

	// Check if body contains updated fields upon confirmation
	var payload UpdateHoldBorrowPayload
	if errBody := c.BodyParser(&payload); errBody == nil {
		if strings.TrimSpace(payload.BorrowerName) != "" {
			r.BorrowerName = strings.TrimSpace(payload.BorrowerName)
			uID, uName, uCompany, found := ResolveUserByBorrowerName(ctx, r.BorrowerName)
			if uID != "" {
				r.BorrowerID = uID
				if found && uName != "" {
					r.BorrowerName = uName
				}
				if uCompany != "" && strings.TrimSpace(payload.GroupName) == "" {
					r.GroupName = uCompany
				}
			}
		}
		if strings.TrimSpace(payload.GroupName) != "" {
			r.GroupName = strings.TrimSpace(payload.GroupName)
		}
		if strings.TrimSpace(payload.Notes) != "" {
			r.Notes = strings.TrimSpace(payload.Notes)
		}
		if len(payload.Items) > 0 {
			var validItems []HoldBorrowItem
			for _, it := range payload.Items {
				it.AssetID = strings.TrimSpace(it.AssetID)
				if it.AssetID == "" {
					continue
				}
				if it.DurationDays <= 0 {
					it.DurationDays = 14
				}
				if it.AssetName == "" || it.Category == "" {
					var aName, aCat string
					_ = DB.QueryRow(ctx, `SELECT name, category FROM public.assets WHERE asset_id ILIKE $1 LIMIT 1`, it.AssetID).Scan(&aName, &aCat)
					if it.AssetName == "" && aName != "" {
						it.AssetName = aName
					}
					if it.Category == "" && aCat != "" {
						it.Category = aCat
					}
				}
				validItems = append(validItems, it)
			}
			if len(validItems) > 0 {
				r.Items = validItems
			}
		}
	}

	if len(r.Items) == 0 {
		return c.Status(400).JSON(fiber.Map{"error": "Permohonan tidak memiliki aset yang dipinjam"})
	}

	// Availability validation: Check table assets, other hold_borrow, and pending/active approval transactions
	_, submitUserCompany := resolveUserContext(c)
	if submitUserCompany == "" {
		submitUserCompany = strings.TrimSpace(c.Get("X-Company"))
	}
	for _, it := range r.Items {
		avail, errMsg := CheckAssetAvailability(ctx, it.AssetID, submitUserCompany, r.ID, "")
		if !avail {
			return c.Status(400).JSON(fiber.Map{"error": errMsg})
		}
	}

	// 1. Generate transaction code TRX-BRW-XXX
	var nextNum int
	_ = DB.QueryRow(ctx, `
		SELECT COALESCE(MAX(SUBSTRING(transaction_code FROM 9)::int), 0) + 1
		FROM public.borrow_transactions
		WHERE transaction_code LIKE 'TRX-BRW-%'
	`).Scan(&nextNum)

	trxCode := fmt.Sprintf("TRX-BRW-%03d", nextNum)

	// 2. Insert into public.borrow_transactions
	var trxID string
	err = DB.QueryRow(ctx, `
		INSERT INTO public.borrow_transactions (
			id, transaction_code, borrower_id, borrower_name, manager_id, manager_name, group_name, request_date, status, created_at
		) VALUES (
			gen_random_uuid(), $1, $2, $3, $4, $5, $6, CURRENT_DATE, 'pending_approval', NOW()
		) RETURNING id
	`, trxCode, r.BorrowerID, r.BorrowerName, r.ManagerID, r.ManagerName, r.GroupName).Scan(&trxID)

	if err != nil {
		return c.Status(500).JSON(fiber.Map{"error": "Gagal membuat transaksi peminjaman resmi: " + err.Error()})
	}

	// 3. Insert items into public.borrow_items
	for _, it := range r.Items {
		dur := it.DurationDays
		if dur <= 0 {
			dur = 14
		}
		var realAssetID string
		_ = DB.QueryRow(ctx, `SELECT asset_id FROM public.assets WHERE asset_id ILIKE $1 LIMIT 1`, it.AssetID).Scan(&realAssetID)
		if realAssetID != "" {
			it.AssetID = realAssetID
		}
		_, errItem := DB.Exec(ctx, `
			INSERT INTO public.borrow_items (
				id, transaction_id, asset_id, duration_days, status
			) VALUES (
				gen_random_uuid(), $1, $2, $3, 'pending'
			)
		`, trxID, it.AssetID, dur)
		if errItem != nil {
			log.Printf("[SubmitHoldBorrow] Error inserting item %s: %v", it.AssetID, errItem)
		}
	}

	// 4. Update status in public.hold_borrow to 'submitted' with latest items and notes
	finalItemsJSON, _ := json.Marshal(r.Items)
	newNotes := strings.TrimSpace(r.Notes + " [Submitted as " + trxCode + "]")
	_, _ = DB.Exec(ctx, `
		UPDATE public.hold_borrow
		SET status = 'submitted', borrower_id = $1, borrower_name = $2, group_name = $3, items = $4, notes = $5, updated_at = NOW()
		WHERE id = $6
	`, r.BorrowerID, r.BorrowerName, r.GroupName, finalItemsJSON, newNotes, r.ID)

	return c.Status(200).JSON(fiber.Map{
		"message":          "Permohonan peminjaman berhasil di-submit ke sistem transaksi!",
		"hold_code":        r.HoldCode,
		"transaction_id":   trxID,
		"transaction_code": trxCode,
		"borrower_name":    r.BorrowerName,
		"items_count":      len(r.Items),
	})
}

