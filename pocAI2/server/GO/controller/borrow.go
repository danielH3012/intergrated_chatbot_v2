// AnomalyThresholds defines configurable limits for detecting transaction anomalies per tenant
type AnomalyThresholds struct {
	CompanyName         string `json:"company_name,omitempty"`
	MaxDurationDays     int    `json:"max_duration_days"`     // default 28: > 28 hari (Sinyal 1)
	MaxActiveLoans      int    `json:"max_active_loans"`      // default 3:  >= 3 pinjaman aktif (Sinyal 2)
	MaxLateReturns      int    `json:"max_late_returns"`      // default 2:  >= 2 telat kembali dalam 6 bulan (Sinyal 3)
	MaxExtensions       int    `json:"max_extensions"`        // default 2:  >= 2 perpanjangan dalam 6 bulan (Sinyal 4)
	MaxAssetCount       int    `json:"max_asset_count"`       // default 5:  > 5 aset dalam 1 permohonan (Sinyal 5)
	AuditWindowDays     int    `json:"audit_window_days"`     // default 7:  <= 7 hari sebelum audit (Sinyal 6)
	RepeatBorrowCycles  int    `json:"repeat_borrow_cycles"`  // default 2:  >= 2 kali pinjam aset sama (Sinyal 7)
	MinSignalsForReview int    `json:"min_signals_for_review"`// default 1:  >= 1 sinyal terpicu = review
}

var (
	anomalyThresholdsLock sync.RWMutex
	fallbackDefaultThresholds = AnomalyThresholds{
		CompanyName:         "qtera mandiri",
		MaxDurationDays:     getIntEnv("ANOMALY_MAX_DURATION_DAYS", 28),
		MaxActiveLoans:      getIntEnv("ANOMALY_MAX_ACTIVE_LOANS", 3),
		MaxLateReturns:      getIntEnv("ANOMALY_MAX_LATE_RETURNS", 2),
		MaxExtensions:       getIntEnv("ANOMALY_MAX_EXTENSIONS", 2),
		MaxAssetCount:       getIntEnv("ANOMALY_MAX_ASSET_COUNT", 5),
		AuditWindowDays:     getIntEnv("ANOMALY_AUDIT_WINDOW_DAYS", 7),
		RepeatBorrowCycles:  getIntEnv("ANOMALY_REPEAT_BORROW_CYCLES", 2),
		MinSignalsForReview: getIntEnv("ANOMALY_MIN_SIGNALS", 1),
	}
)

func getIntEnv(key string, fallback int) int {
	if val := os.Getenv(key); val != "" {
		if parsed, err := strconv.Atoi(strings.TrimSpace(val)); err == nil && parsed > 0 {
			return parsed
		}
	}
	return fallback
}

// EnsureBorrowThresholdSettingsTable creates the public.borrow_threshold_settings table,
// adds an automatic trigger to seed default thresholds whenever a new perusahaan is added,
// and seeds records for existing tenants.
func EnsureBorrowThresholdSettingsTable(ctx context.Context) error {
	if DB == nil {
		return fmt.Errorf("database connection pool is not initialized")
	}

	createTableSQL := `
	CREATE TABLE IF NOT EXISTS public.perusahaan (
		id_perusahaan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		nama_perusahaan VARCHAR(125)
	);

	CREATE TABLE IF NOT EXISTS public.borrow_threshold_settings (
		id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
		company_name VARCHAR(125) NOT NULL UNIQUE,
		max_duration_days INT NOT NULL DEFAULT 28,
		max_active_loans INT NOT NULL DEFAULT 3,
		max_late_returns INT NOT NULL DEFAULT 2,
		max_extensions INT NOT NULL DEFAULT 2,
		max_asset_count INT NOT NULL DEFAULT 5,
		audit_window_days INT NOT NULL DEFAULT 7,
		repeat_borrow_cycles INT NOT NULL DEFAULT 2,
		min_signals_for_review INT NOT NULL DEFAULT 1,
		created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
		updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
	);

	CREATE OR REPLACE FUNCTION trg_auto_create_borrow_thresholds()
	RETURNS TRIGGER AS $$
	BEGIN
		INSERT INTO public.borrow_threshold_settings (company_name)
		VALUES (NEW.nama_perusahaan)
		ON CONFLICT (company_name) DO NOTHING;
		RETURN NEW;
	END;
	$$ LANGUAGE plpgsql;

	DROP TRIGGER IF EXISTS trg_perusahaan_insert_thresholds ON public.perusahaan;
	CREATE TRIGGER trg_perusahaan_insert_thresholds
	AFTER INSERT ON public.perusahaan
	FOR EACH ROW
	EXECUTE FUNCTION trg_auto_create_borrow_thresholds();

	INSERT INTO public.borrow_threshold_settings (company_name)
	SELECT DISTINCT nama_perusahaan FROM public.perusahaan 
	WHERE nama_perusahaan IS NOT NULL AND TRIM(nama_perusahaan) != ''
	ON CONFLICT (company_name) DO NOTHING;

	INSERT INTO public.borrow_threshold_settings (company_name)
	VALUES ('qtera mandiri')
	ON CONFLICT (company_name) DO NOTHING;
	`

	_, err := DB.Exec(ctx, createTableSQL)
	if err != nil {
		log.Printf("[EnsureBorrowThresholdSettingsTable] Failed to bootstrap public.borrow_threshold_settings: %v", err)
		return err
	}
	log.Println("[EnsureBorrowThresholdSettingsTable] Table public.borrow_threshold_settings and auto-creation trigger verified successfully.")
	return nil
}

// ResolveTenantCompany resolves the company / tenant name for the current request
func ResolveTenantCompany(c *fiber.Ctx) string {
	company := ""
	if id := middleware.RequestIdentity(c); id != nil {
		company = strings.TrimSpace(id.Company)
		if company == "" && id.IdPerusahaan > 0 && DB != nil {
			_ = DB.QueryRow(c.Context(), `SELECT nama_perusahaan FROM public.perusahaan WHERE id_perusahaan = $1 LIMIT 1`, id.IdPerusahaan).Scan(&company)
		}
	}
	if company == "" {
		company = strings.TrimSpace(c.Get("X-Company"))
	}
	if company == "" {
		company = strings.TrimSpace(c.Get("X-Company-Name"))
	}
	if company == "" {
		company = strings.TrimSpace(c.Get("X-Tenant-ID"))
	}
	if company == "" {
		company = strings.TrimSpace(c.Query("group_name"))
	}
	if company == "" {
		company = strings.TrimSpace(c.Query("company"))
	}
	if company == "" {
		company = "qtera mandiri"
	}
	return company
}

// GetTenantThresholds retrieves anomaly thresholds from the DB for a given tenant,
// automatically seeding default thresholds if the tenant does not exist yet.
func GetTenantThresholds(ctx context.Context, company string) AnomalyThresholds {
	company = strings.TrimSpace(company)
	if company == "" {
		company = "qtera mandiri"
	}

	defaultCfg := fallbackDefaultThresholds
	defaultCfg.CompanyName = company

	if DB == nil {
		return defaultCfg
	}

	var matchedCompany string
	err := DB.QueryRow(ctx, `SELECT company_name FROM public.borrow_threshold_settings WHERE LOWER(TRIM(company_name)) = LOWER(TRIM($1)) LIMIT 1`, company).Scan(&matchedCompany)
	if err == nil && matchedCompany != "" {
		company = matchedCompany
	} else {
		// Automatically create default settings row for this tenant
		_, _ = DB.Exec(ctx, `
			INSERT INTO public.borrow_threshold_settings (company_name)
			VALUES ($1)
			ON CONFLICT (company_name) DO NOTHING
		`, company)
	}

	row := DB.QueryRow(ctx, `
		SELECT company_name, max_duration_days, max_active_loans, max_late_returns,
		       max_extensions, max_asset_count, audit_window_days, repeat_borrow_cycles, min_signals_for_review
		FROM public.borrow_threshold_settings
		WHERE LOWER(TRIM(company_name)) = LOWER(TRIM($1))
		LIMIT 1
	`, company)

	var res AnomalyThresholds
	if err := row.Scan(
		&res.CompanyName,
		&res.MaxDurationDays,
		&res.MaxActiveLoans,
		&res.MaxLateReturns,
		&res.MaxExtensions,
		&res.MaxAssetCount,
		&res.AuditWindowDays,
		&res.RepeatBorrowCycles,
		&res.MinSignalsForReview,
	); err != nil {
		return defaultCfg
	}

	return res
}

// UpdateTenantThresholds updates the threshold values for a specific tenant in the database
func UpdateTenantThresholds(ctx context.Context, company string, newCfg AnomalyThresholds) (AnomalyThresholds, error) {
	company = strings.TrimSpace(company)
	if company == "" {
		company = "qtera mandiri"
	}

	curr := GetTenantThresholds(ctx, company)
	if newCfg.MaxDurationDays > 0 {
		curr.MaxDurationDays = newCfg.MaxDurationDays
	}
	if newCfg.MaxActiveLoans > 0 {
		curr.MaxActiveLoans = newCfg.MaxActiveLoans
	}
	if newCfg.MaxLateReturns > 0 {
		curr.MaxLateReturns = newCfg.MaxLateReturns
	}
	if newCfg.MaxExtensions > 0 {
		curr.MaxExtensions = newCfg.MaxExtensions
	}
	if newCfg.MaxAssetCount > 0 {
		curr.MaxAssetCount = newCfg.MaxAssetCount
	}
	if newCfg.AuditWindowDays > 0 {
		curr.AuditWindowDays = newCfg.AuditWindowDays
	}
	if newCfg.RepeatBorrowCycles > 0 {
		curr.RepeatBorrowCycles = newCfg.RepeatBorrowCycles
	}
	if newCfg.MinSignalsForReview > 0 {
		curr.MinSignalsForReview = newCfg.MinSignalsForReview
	}

	if DB == nil {
		return curr, fmt.Errorf("database connection pool is not initialized")
	}

	_, err := DB.Exec(ctx, `
		INSERT INTO public.borrow_threshold_settings (
			company_name, max_duration_days, max_active_loans, max_late_returns,
			max_extensions, max_asset_count, audit_window_days, repeat_borrow_cycles,
			min_signals_for_review, updated_at
		) VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9, NOW())
		ON CONFLICT (company_name) DO UPDATE SET
			max_duration_days = EXCLUDED.max_duration_days,
			max_active_loans = EXCLUDED.max_active_loans,
			max_late_returns = EXCLUDED.max_late_returns,
			max_extensions = EXCLUDED.max_extensions,
			max_asset_count = EXCLUDED.max_asset_count,
			audit_window_days = EXCLUDED.audit_window_days,
			repeat_borrow_cycles = EXCLUDED.repeat_borrow_cycles,
			min_signals_for_review = EXCLUDED.min_signals_for_review,
			updated_at = NOW()
	`, curr.CompanyName, curr.MaxDurationDays, curr.MaxActiveLoans, curr.MaxLateReturns,
		curr.MaxExtensions, curr.MaxAssetCount, curr.AuditWindowDays,
		curr.RepeatBorrowCycles, curr.MinSignalsForReview)

	if err != nil {
		return curr, err
	}
	return curr, nil
}

