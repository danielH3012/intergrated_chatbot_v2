// SetAnomalyThresholdsConfig updates the active anomaly thresholds (fallback)
func SetAnomalyThresholdsConfig(newCfg AnomalyThresholds) AnomalyThresholds {
	updated, _ := UpdateTenantThresholds(context.Background(), "qtera mandiri", newCfg)
	return updated
}

